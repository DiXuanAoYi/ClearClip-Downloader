// 剪辑页面新增的整理操作：添加素材菜单、向左/右裁剪、波纹删除、分离音频、剪辑点/逐帧、复制、应用到全部、最近工程、吸附、Ctrl+滚轮缩放。
const { launch, openHarness, m, OUT, addMenu } = require('./lib.cjs')

let pass = 0
let fail = 0
const ok = (name, cond, extra = '') => {
  if (cond) pass++
  else fail++
  console.log(`${cond ? '  ok ' : 'FAIL '} ${name}${cond ? '' : '  ← ' + extra}`)
}
const close = (a, b, tol) => Math.abs(a - b) <= tol

;(async () => {
  const { srv, browser, page, errors } = await launch()
  await openHarness(page, errors)

  const parseT = (s) => {
    const mm = /^(\d+):(\d{2})(?:\.(\d+))?$/.exec(s.trim())
    return mm ? (+mm[1] * 60 + +mm[2]) * 1000 + (mm[3] ? Math.round(+('0.' + mm[3]) * 1000) : 0) : NaN
  }
  const clips = () =>
    page.$$eval('.blk.clip', (els) =>
      els.map((e) => {
        const r = e.getBoundingClientRect()
        return { name: e.querySelector('.cap')?.textContent.trim(), x: r.x, w: r.width, y: r.y, h: r.height, sel: e.classList.contains('sel') }
      }),
    )
  const total = async () => parseT(await page.locator('.info .mono').first().textContent())
  const playhead = async () => parseT((await page.locator('.time').textContent()).split('/')[0])
  const pps = async () => {
    const t = await page.$$eval('.tick', (els) => els.slice(0, 3).map((e) => ({ left: parseFloat(e.style.left), label: e.textContent.trim() })))
    const secs = parseT(t[1].label.includes('.') ? t[1].label : t[1].label + '.0')
    return t[1].left / (secs / 1000)
  }
  const rulerX = async (ms) => (await page.locator('.ruler').boundingBox()).x + (ms / 1000) * (await pps())
  const seekTo = async (ms) => {
    const r = await page.locator('.ruler').boundingBox()
    await page.mouse.click(await rulerX(ms), r.y + 10)
  }
  const field = (label) => page.locator('.insp .f', { has: page.locator(`.n:text-is("${label}")`) })
  const dialogOpen = (v) => page.evaluate((a) => (window.__dialogOpen = [a]), v)
  const settle = (ms = 150) => page.waitForTimeout(ms)
  // 工程内容：草稿 800ms 后写进 localStorage，直接读它比读界面可靠
  const proj = async () => {
    await page.waitForTimeout(1000)
    return page.evaluate(() => JSON.parse(localStorage.getItem('clearclip.edit.draft') || 'null')?.project)
  }
  const clickClip = async (i) => {
    const c = (await clips())[i]
    await page.mouse.click(c.x + c.w / 2, c.y + c.h / 2)
    await settle(100)
  }
  const barBtn = (name) => page.locator('.tlbar').getByRole('button', { name, exact: true })

  // ---- 工具栏整合 ----
  console.log('# 工具栏')
  ok('只有一个“添加素材”入口（不再有六个添加按钮）', (await page.locator('.bar').getByRole('button', { name: /添加到主轨|添加叠加素材|添加配乐|从媒体库/ }).count()) === 0)
  ok('“回到开头”按钮已删除', (await page.getByRole('button', { name: '回到开头' }).count()) === 0)
  ok('没有素材时不显示预览状态条', (await page.locator('.pvbar').count()) === 0)
  await dialogOpen([m('red.webm'), m('green.webm')])
  await addMenu(page, '添加到主轨…')
  await page.waitForFunction(() => document.querySelectorAll('.blk.clip').length === 2)
  await settle(400)
  ok('点“添加素材”按钮本身是加到主轨', (await clips()).length === 2)
  await dialogOpen([m('music.ogg')])
  await addMenu(page, '添加配乐…')
  await page.waitForSelector('.blk.aud')
  ok('菜单里的“添加配乐”能加配乐', (await page.locator('.blk.aud').count()) === 1)
  await page.keyboard.press('Control+z')
  await settle(200)
  ok('撤销配乐', (await page.locator('.blk.aud').count()) === 0)
  await page.locator('.bar .el-dropdown', { hasText: '添加素材' }).locator('.el-dropdown__caret-button').click()
  await settle(300)
  ok('菜单有 6 项（主轨、叠加、配乐，各有媒体库）', (await page.getByRole('menuitem').count()) >= 6)
  await page.keyboard.press('Escape')
  await settle(200)

  // ---- 快捷键说明 ----
  console.log('# 快捷键说明')
  await page.locator('.tlbar').getByRole('button', { name: '快捷键' }).click()
  await settle(200)
  const kbds = await page.locator('.keys kbd').allTextContents()
  ok('快捷键面板列出新增的快捷键', ['Q / W', 'Shift+Delete', 'Ctrl+D', ', .', '[ ]', 'Ctrl+滚轮'].every((k) => kbds.includes(k)), JSON.stringify(kbds))
  await page.mouse.click(5, 5)
  await settle(200)

  // ---- 逐帧、剪辑点 ----
  console.log('# 逐帧与剪辑点')
  await seekTo(0)
  await settle(200)
  for (let i = 0; i < 5; i++) await page.keyboard.press('.')
  await settle(150)
  ok('按 5 次 “.” 前进 5 帧 ≈ 0.2 秒（25 帧/秒）', close(await playhead(), 200, 60), String(await playhead()))
  await page.keyboard.press(',')
  await settle(100)
  ok('按 “,” 后退一帧 ≈ 0.16 秒', close(await playhead(), 160, 60), String(await playhead()))
  await page.keyboard.press(']')
  await settle(100)
  ok('按 “]” 跳到下一个剪辑点（第一个片段的结尾 ≈ 6 秒）', close(await playhead(), 6000, 150), String(await playhead()))
  await page.keyboard.press(']')
  await settle(100)
  ok('再按一次跳到结尾 ≈ 11 秒', close(await playhead(), 11000, 150), String(await playhead()))
  await page.keyboard.press(']')
  await settle(100)
  ok('已经在结尾，位置不变', close(await playhead(), 11000, 150), String(await playhead()))
  await page.keyboard.press('[')
  await settle(100)
  ok('按 “[” 回到上一个剪辑点 ≈ 6 秒', close(await playhead(), 6000, 150), String(await playhead()))
  await page.getByRole('button', { name: '«' }).click()
  await settle(100)
  ok('按钮 « 回到更前面的剪辑点（0 秒）', close(await playhead(), 0, 150), String(await playhead()))
  await page.getByRole('button', { name: '›' }).click()
  await settle(100)
  ok('按钮 › 前进一帧', close(await playhead(), 40, 30), String(await playhead()))

  // ---- 向左 / 向右裁剪 ----
  console.log('# 向左/向右裁剪')
  await clickClip(0)
  await seekTo(2000)
  await settle(150)
  const t0 = await total()
  await page.keyboard.press('q')
  await settle(150)
  ok('Q：去掉播放位置左边的 2 秒，总长少 2 秒', close(await total(), t0 - 2000, 150), `${t0} → ${await total()}`)
  let p = await proj()
  ok('入点移到了 2 秒', close(p.clips[0].inMs, 2000, 60), String(p.clips[0].inMs))
  await page.keyboard.press('Control+z')
  await settle(200)
  ok('Ctrl+Z 撤销裁剪', close(await total(), t0, 150), String(await total()))
  await clickClip(0)
  await seekTo(2000)
  await page.keyboard.press('w')
  await settle(150)
  p = await proj()
  ok('W：去掉播放位置右边的部分，出点 ≈ 2 秒', close(p.clips[0].outMs, 2000, 60), String(p.clips[0].outMs))
  await page.keyboard.press('Control+z')
  await settle(200)
  await barBtn('向左裁剪').click()
  await settle(150)
  p = await proj()
  ok('按钮“向左裁剪”和 Q 一样', close(p.clips[0].inMs, 2000, 60), String(p.clips[0].inMs))
  await page.keyboard.press('Control+z')
  await settle(200)
  await seekTo(10)
  await barBtn('向右裁剪').click()
  await settle(200)
  ok('离片段开头太近时给出提示、不改动', (await page.locator('.el-message').allTextContents()).join().includes('至少 0.1 秒') && close(await total(), t0, 150), String(await total()))
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))

  // ---- 复制 ----
  console.log('# 复制')
  await clickClip(1)
  await page.keyboard.press('Control+d')
  await settle(200)
  ok('Ctrl+D 复制选中的片段', (await clips()).length === 3)
  await page.keyboard.press('Control+z')
  await settle(200)
  ok('撤销复制', (await clips()).length === 2)

  // ---- 分离音频 ----
  console.log('# 分离音频')
  await page.mouse.click(5, 5)
  await settle(100)
  ok('没有选中任何东西时“分离音频”不可用', await barBtn('分离音频').isDisabled())
  await clickClip(0)
  ok('选中带声音的片段后可用', await barBtn('分离音频').isEnabled())
  await barBtn('分离音频').click()
  await settle(300)
  p = await proj()
  ok('配乐轨多了一条同一个文件的声音，从 0 秒开始', p.audio.length === 1 && p.audio[0].path.endsWith('red.webm') && p.audio[0].startMs === 0, JSON.stringify(p.audio))
  ok('原来的片段静音了', p.clips[0].mute === true)
  ok('选中跳到了新的配乐', (await page.locator('.blk.aud.sel').count()) === 1)
  await clickClip(0)
  await barBtn('分离音频').click()
  await settle(200)
  ok('已静音的片段再分离会说明原因', (await page.locator('.el-message').allTextContents()).join().includes('静音'))
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))
  await page.keyboard.press('Control+z')
  await settle(200)
  p = await proj()
  ok('一次撤销同时还原配乐和静音', p.audio.length === 0 && p.clips[0].mute === false, JSON.stringify([p.audio.length, p.clips[0].mute]))

  // ---- 波纹删除 ----
  console.log('# 波纹删除')
  await seekTo(7000)
  await dialogOpen([m('music.ogg')])
  await addMenu(page, '添加配乐…')
  await page.waitForSelector('.blk.aud')
  await page.getByRole('button', { name: '添加文字' }).click()
  await settle(200)
  p = await proj()
  const audioAt = p.audio[0].startMs
  ok('配乐从 7 秒开始', close(audioAt, 7000, 150), String(audioAt))
  ok('文字也在 7 秒', close(p.texts[0].startMs, 7000, 150), String(p.texts[0].startMs))
  await clickClip(0)
  ok('选中主轨片段时出现“波纹删除”', (await barBtn('波纹删除').count()) === 1)
  await page.keyboard.press('Shift+Delete')
  await settle(300)
  p = await proj()
  ok('红色片段被删了，只剩绿色', p.clips.length === 1 && p.clips[0].path.endsWith('green.webm'))
  ok('配乐前移了被删片段的长度（≈ 1 秒）', close(p.audio[0].startMs, audioAt - 6000, 150), String(p.audio[0].startMs))
  ok('文字也前移了，长度不变', close(p.texts[0].startMs, 1000, 150) && close(p.texts[0].endMs - p.texts[0].startMs, 3000, 10), JSON.stringify(p.texts[0]))
  ok('提示后面的内容一起前移了', (await page.locator('.el-message').allTextContents()).join().includes('一起前移'))
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))
  await page.keyboard.press('Control+z')
  await settle(250)
  p = await proj()
  ok('一次撤销全部还原', p.clips.length === 2 && close(p.audio[0].startMs, audioAt, 5) && close(p.texts[0].startMs, 7000, 150))
  await clickClip(0)
  await page.keyboard.press('Delete')
  await settle(250)
  p = await proj()
  ok('普通 Delete 不动后面的内容', p.clips.length === 1 && close(p.audio[0].startMs, audioAt, 5), JSON.stringify([p.clips.length, p.audio[0].startMs]))
  await page.keyboard.press('Control+z')
  await settle(200)

  // ---- 应用到全部片段 ----
  console.log('# 应用到全部片段')
  await dialogOpen([m('blue.webm')])
  await addMenu(page, '添加到主轨…')
  await page.waitForFunction(() => document.querySelectorAll('.blk.clip').length === 3)
  await settle(300)
  await clickClip(0)
  ok('只有一个片段被选中时才有“应用到全部片段”', (await page.getByRole('button', { name: '应用到全部片段' }).count()) === 2)
  await field('亮度').locator('.el-slider__button-wrapper').focus()
  for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowRight')
  await settle(200)
  await page.getByRole('button', { name: '右转 90°' }).click().catch(() => undefined)
  await settle(100)
  p = await proj()
  const b0 = p.clips[0].brightness
  ok('第一个片段调亮了', b0 > 0.03, String(b0))
  ok('其它片段还没变', p.clips[1].brightness === 0 && p.clips[2].brightness === 0)
  await page.getByRole('button', { name: '应用到全部片段' }).nth(1).click()
  await settle(300)
  p = await proj()
  ok('调色应用到所有片段', p.clips.every((c) => c.brightness === b0 && c.contrast === p.clips[0].contrast), JSON.stringify(p.clips.map((c) => c.brightness)))
  ok('提示应用到其他 2 个片段', (await page.locator('.el-message').allTextContents()).join().includes('其他 2 个片段'))
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))
  ok('画面方向没跟着变', p.clips.every((c) => c.rotate === p.clips[0].rotate) === (p.clips[0].rotate === 0))
  await page.getByRole('button', { name: '应用到全部片段' }).first().click()
  await settle(300)
  p = await proj()
  ok('画面方向应用到所有片段', p.clips.every((c) => c.rotate === p.clips[0].rotate && c.flipH === p.clips[0].flipH))
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))

  // 转场
  await clickClip(1)
  await field('转场').locator('.el-select').click()
  await page.getByRole('option', { name: '淡入淡出' }).click()
  await settle(200)
  ok('第二个片段有了转场', (await clips())[1] && (await page.locator('.xf').count()) === 1)
  await page.getByRole('button', { name: '应用到所有衔接处' }).click()
  await settle(300)
  p = await proj()
  ok('转场应用到所有衔接处（第一个片段前面没有）', p.clips[0].transition === null && p.clips[1].transition?.kind === 'fade' && p.clips[2].transition?.kind === 'fade' && p.clips[2].transition.durationMs === p.clips[1].transition.durationMs, JSON.stringify(p.clips.map((c) => c.transition)))
  ok('时间线上两处都有转场标记', (await page.locator('.xf').count()) === 2)
  await page.getByRole('button', { name: '去掉所有转场' }).click()
  await settle(300)
  p = await proj()
  ok('去掉所有转场', p.clips.every((c) => c.transition === null) && (await page.locator('.xf').count()) === 0)
  await page.keyboard.press('Control+z')
  await settle(200)
  ok('撤销去掉所有转场', (await page.locator('.xf').count()) === 2)
  await page.evaluate(() => document.querySelectorAll('.el-message').forEach((e) => e.remove()))

  // ---- 吸附 ----
  console.log('# 吸附')
  const snapBox = page.locator('.tlbar .el-checkbox', { hasText: '吸附' })
  ok('吸附默认开着', await snapBox.locator('input').isChecked())
  await snapBox.click()
  await settle(100)
  ok('点一下关闭吸附', !(await snapBox.locator('input').isChecked()))
  ok('吸附开关被记住', (await page.evaluate(() => localStorage.getItem('clearclip.edit.snap'))) === '0')
  await snapBox.click()
  await settle(100)
  ok('再点一下重新打开', (await page.evaluate(() => localStorage.getItem('clearclip.edit.snap'))) === '1')

  // ---- Ctrl+滚轮缩放 ----
  console.log('# Ctrl+滚轮缩放')
  const z0 = await pps()
  const tl = await page.locator('.tl').boundingBox()
  await page.mouse.move(tl.x + tl.width / 2, tl.y + 40)
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, -200)
  await page.keyboard.up('Control')
  await settle(300)
  const z1 = await pps()
  ok('Ctrl+向上滚放大时间线', z1 > z0 * 1.1, `${z0} → ${z1}`)
  ok('缩放滑块跟着变', Math.abs(Number(await page.locator('.zoom .el-slider__button-wrapper').getAttribute('aria-valuenow')) - z1) <= 1)
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, 400)
  await page.keyboard.up('Control')
  await settle(300)
  const z2 = await pps()
  ok('Ctrl+向下滚缩小', z2 < z1 * 0.9, `${z1} → ${z2}`)
  const sx = await page.evaluate(() => document.querySelector('.tl').scrollLeft)
  await page.mouse.wheel(0, 300)
  await settle(200)
  ok('不按 Ctrl 的滚轮不缩放', close(await pps(), z2, 0.5))

  // ---- 最近的工程 ----
  console.log('# 最近的工程')
  await page.evaluate(() => (window.__dialogSave = ['/tmp/ops-a.ccedit']))
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await settle(400)
  const recent = await page.evaluate(() => JSON.parse(localStorage.getItem('clearclip.edit.recent') || '[]'))
  ok('保存后记入最近的工程', recent[0] === '/tmp/ops-a.ccedit', JSON.stringify(recent))
  await page.getByRole('button', { name: '新建' }).click()
  await page.getByRole('button', { name: '放弃修改' }).click({ timeout: 1500 }).catch(() => undefined)
  await settle(300)
  ok('新建后时间线是空的', (await page.locator('.blk.clip').count()) === 0)
  await page.locator('.bar .el-dropdown', { hasText: '打开…' }).locator('.el-dropdown__caret-button').click()
  await settle(300)
  ok('“打开”的菜单里列出最近的工程', (await page.getByRole('menuitem', { name: 'ops-a.ccedit' }).count()) === 1)
  await page.getByRole('menuitem', { name: 'ops-a.ccedit' }).click()
  await page.waitForFunction(() => document.querySelectorAll('.blk.clip').length === 3, null, { timeout: 8000 })
  ok('点菜单里的工程直接打开（不用再选文件）', (await clips()).length === 3)
  // 文件没了：提示并从列表里去掉
  await page.evaluate(() => {
    delete window.__files['/tmp/ops-a.ccedit']
  })
  await page.getByRole('button', { name: '新建' }).click()
  await page.getByRole('button', { name: '放弃修改' }).click({ timeout: 1500 }).catch(() => undefined)
  await settle(300)
  await page.locator('.bar .el-dropdown', { hasText: '打开…' }).locator('.el-dropdown__caret-button').click()
  await page.getByRole('menuitem', { name: 'ops-a.ccedit' }).click()
  await settle(500)
  ok('打不开时给出提示', (await page.locator('.el-message').allTextContents()).join().includes('已从最近的列表里去掉'))
  ok('打不开的工程从最近的列表里去掉了', (await page.evaluate(() => JSON.parse(localStorage.getItem('clearclip.edit.recent') || '[]'))).length === 0)
  await page.screenshot({ path: OUT + '/ops-final.png' })

  const bad = errors.filter((e) => !/favicon|net::ERR|Failed to load resource/.test(e))
  ok('没有控制台错误', bad.length === 0, bad.slice(0, 3).join(' | '))
  console.log(`\n通过 ${pass}，失败 ${fail}`)
  await browser.close()
  srv.close()
  process.exit(fail ? 1 : 0)
})().catch((e) => {
  console.error(e)
  process.exit(2)
})
