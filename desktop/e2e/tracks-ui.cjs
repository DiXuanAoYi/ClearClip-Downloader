// 多轨道：每一类都能有很多条轨道、轨道头开关、类型菜单、插入 / 删除轨道、调整图层、刀片、标记、入点出点、音量线。
const { launch, openHarness, m, addMenu } = require('./lib.cjs')

let pass = 0
let fail = 0
const ok = (name, cond, extra = '') => {
  if (cond) pass++
  else fail++
  console.log(`${cond ? '  ok ' : 'FAIL '} ${name}${cond ? '' : '  ← ' + extra}`)
}

;(async () => {
  const { srv, browser, page, errors } = await launch()
  await openHarness(page, errors)
  const settle = (ms = 150) => page.waitForTimeout(ms)
  const dialogOpen = (v) => page.evaluate((a) => (window.__dialogOpen = [a]), v)
  const proj = async () => {
    await page.waitForTimeout(1000)
    return page.evaluate(() => JSON.parse(localStorage.getItem('clearclip.edit.draft') || 'null')?.project)
  }
  const codes = () => page.$$eval('.row[data-kind] .th .chip', (els) => els.map((e) => e.textContent.replace('▾', '').trim()))
  const head = (code) => page.locator('.row[data-kind] .th', { has: page.locator('.chip', { hasText: new RegExp(`^${code}`) }) }).first()
  const menuItem = (name) => page.locator('.tmenu .it', { hasText: name }).first()

  console.log('# 基本')
  await dialogOpen([m('red.webm'), m('green.webm')])
  await addMenu(page, '添加到主轨…')
  await page.waitForFunction(() => document.querySelectorAll('.blk.clip').length === 2)
  await settle(300)
  const base = await codes()
  ok('一开始就有 T1、V1、A1 三条基本轨道', ['T1', 'V1', 'A1'].every((c) => base.includes(c)), base.join(','))
  ok('V1 叫“主轨”，带“磁吸”标记', (await head('V1').innerText()).includes('主轨') && (await head('V1').innerText()).includes('磁吸'))

  console.log('# 叠加素材 = V2 起的视频轨，重叠的自动放到新轨')
  await dialogOpen([m('blue.webm')])
  await addMenu(page, '添加叠加素材…')
  await page.waitForSelector('.blk.ovl')
  await dialogOpen([m('yellow.png')])
  await addMenu(page, '添加叠加素材…')
  await page.waitForFunction(() => document.querySelectorAll('.blk.ovl').length === 2)
  await settle(300)
  const c2 = await codes()
  ok('两个同时出现的叠加素材：V2、V3 各一条', c2.includes('V2') && c2.includes('V3'), c2.join(','))
  ok('V3 在 V2 的上面', (await head('V3').boundingBox()).y < (await head('V2').boundingBox()).y)
  const p1 = await proj()
  ok('两个叠加素材在不同的轨道上', new Set(p1.overlays.map((o) => o.track)).size === 2, JSON.stringify(p1.overlays.map((o) => o.track)))

  console.log('# 配乐：重叠的分到 A1、A2')
  await dialogOpen([m('music.ogg')])
  await addMenu(page, '添加配乐…')
  await page.waitForSelector('.blk.aud')
  await dialogOpen([m('music.ogg')])
  await addMenu(page, '添加配乐…')
  await page.waitForFunction(() => document.querySelectorAll('.blk.aud').length === 2)
  await settle(300)
  const c3 = await codes()
  ok('两条重叠的配乐在 A1、A2 两条轨道上', c3.includes('A1') && c3.includes('A2'), c3.join(','))
  const p2 = await proj()
  ok('工程里两条音频的轨道编号不同', p2.audio[0].track !== p2.audio[1].track, JSON.stringify(p2.audio.map((a) => a.track)))

  console.log('# 新建轨道和类型')
  await page.getByRole('button', { name: /＋ 视频轨/ }).click()
  await settle(100)
  ok('点“＋ 视频轨”弹出类型：画中画 / 全屏 / 调整图层 / 绿幕', (await page.locator('.tmenu .it').allInnerTexts()).join('|').match(/画中画.*全屏.*调整图层.*绿幕/s) !== null)
  await menuItem('全屏').click()
  await settle(200)
  ok('新建了一条“全屏”类型的空轨道 V4', (await codes()).includes('V4') && (await head('V4').innerText()).includes('全屏'))
  await page.getByRole('button', { name: '＋ 文字轨' }).click()
  await settle(150)
  ok('＋ 文字轨：多了 T2', (await codes()).includes('T2'))

  console.log('# 点轨道编号换类型')
  await head('V2').locator('.chip').click()
  await settle(100)
  await menuItem('画中画').click()
  await settle(200)
  ok('V2 改成画中画，轨道头标出“画中画”', (await head('V2').innerText()).includes('画中画'))

  console.log('# 轨道头开关')
  await head('A1').getByRole('button', { name: '静音' }).click()
  await settle(100)
  await head('A2').getByRole('button', { name: '独奏' }).click()
  await head('V3').getByRole('button', { name: '锁定' }).click()
  await head('V3').getByRole('button', { name: '隐藏' }).click()
  const p3 = await proj()
  const meta = (k, n) => p3.tracks.find((t) => t.kind === k && t.no === n) ?? p3.tracks.find((t) => t.kind === k && t.no === n)
  const p4 = await proj()
  const tr = (k, n) => p4.tracks.find((t) => t.kind === k && t.no === n)
  ok('A1 静音、A2 独奏、V3（叠加轨 2）锁定并隐藏都记进了工程', tr('audio', 1)?.mute === true && tr('audio', 2)?.solo === true && tr('video', 2)?.lock === true && tr('video', 2)?.hidden === true, JSON.stringify(p4.tracks))
  ok('锁定的轨道有锁定样式', (await page.locator('.row.locked').count()) >= 1)
  void meta

  console.log('# 右键菜单：插入、上移、删除')
  const before = (await codes()).length
  await head('V2').click({ button: 'right' })
  await settle(100)
  await menuItem('在上方插入视频轨').click()
  await settle(200)
  ok('在上方插入一条视频轨：总数 +1', (await codes()).length === before + 1, `${before} → ${(await codes()).length}`)
  await head('A2').click({ button: 'right' })
  await settle(100)
  ok('音频轨菜单里有“自动避让”', (await menuItem('自动避让').count()) === 1)
  await page.keyboard.press('Escape')
  await head('T2').click({ button: 'right' })
  await settle(100)
  await menuItem('删除 T2').click()
  await settle(200)
  ok('删掉空的 T2', !(await codes()).includes('T2'))

  console.log('# 调整图层')
  await page.getByRole('button', { name: /＋ 视频轨/ }).click()
  await menuItem('调整图层').click()
  await settle(300)
  const p5 = await proj()
  ok('新建调整图层轨道，并放进一段调整图层', p5.overlays.some((o) => o.adjust === true && o.path === ''), JSON.stringify(p5.overlays.map((o) => [o.adjust, o.track])))
  ok('时间线上有“调整图层”素材条', (await page.locator('.blk.ovl.adj').count()) === 1)

  console.log('# 刀片、标记、入点出点')
  const clipsBefore = await page.locator('.blk.clip').count()
  await page.keyboard.press('b')
  await settle(80)
  const c = await page.locator('.blk.clip').first().boundingBox()
  await page.mouse.click(c.x + c.width / 2, c.y + c.height / 2)
  await settle(300)
  ok('刀片：点一下，主轨多出一个片段', (await page.locator('.blk.clip').count()) === clipsBefore + 1, `${clipsBefore} → ${await page.locator('.blk.clip').count()}`)
  await page.keyboard.press('a')
  await page.keyboard.press('m')
  await settle(200)
  ok('按 M 打一个标记', (await page.locator('.mk').count()) === 1)
  await page.keyboard.press('i')
  await settle(100)
  const p6 = await proj()
  ok('I 设入点（只在播放位置大于 0 时有意义，这里至少不报错）', p6.out.fromMs >= 0 && p6.markers.length === 1)

  console.log('# 混音器和轨道模板')
  await page.getByRole('button', { name: '混音器', exact: true }).click()
  await settle(200)
  ok('混音器里列出每条音频轨', (await page.locator('.mixer .ch').count()) >= 2)
  await page.locator('.mixer .ch').first().getByText('自动避让').click()
  await settle(150)
  const p7 = await proj()
  ok('混音器里打开“自动避让”：记进这条音频轨', p7.tracks.some((t) => t.kind === 'audio' && t.duck === true), JSON.stringify(p7.tracks.filter((t) => t.kind === 'audio')))
  await page.getByRole('button', { name: '混音器', exact: true }).click()
  await page.getByRole('button', { name: /轨道模板/ }).click()
  await settle(100)
  ok('轨道模板菜单有内置模板', (await page.locator('.tmenu .it', { hasText: '播客' }).count()) === 1)
  await page.locator('.tmenu .it', { hasText: '播客' }).click()
  await settle(300)
  const c4 = await codes()
  ok('套用“播客”：A3 音效轨出现', c4.includes('A3'), c4.join(','))
  const p8 = await proj()
  ok('模板里的名字写进了轨道', p8.tracks.some((t) => t.kind === 'audio' && t.no === 2 && t.name === '配乐' && t.duck === true))

  console.log('# 没有脚本错误')
  const real = errors.filter((e) => !/favicon/.test(e))
  ok('页面没有报错', real.length === 0, real.join('; '))
  console.log(`\n${pass} 通过，${fail} 失败`)
  await browser.close()
  srv.kill?.()
  process.exit(fail ? 1 : 0)
})()
