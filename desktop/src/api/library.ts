import { invoke } from '@tauri-apps/api/core'
import type {
  Excerpt,
  VideoCacheInfo,
  VideoCacheFull,
  BackupInfo,
  Chapter,
  CueHit,
  DeleteReport,
  DupGroup,
  ImportReport,
  LibraryStats,
  MovePlan,
  MoveReport,
  SceneList,
  TagCount,
  TrashItem,
  LibraryFilter,
  PlatformCount,
  LibraryItem,
} from '../types'

export const libraryApi = {
  listLibrary: (filter?: Partial<LibraryFilter>) => invoke<LibraryItem[]>('list_library', { filter }),
  libraryPlatforms: () => invoke<PlatformCount[]>('library_platforms'),
  deleteLibrary: (id: number, deleteFile: boolean) => invoke<void>('delete_library', { id, deleteFile }),

  libraryDelete: (ids: number[], deleteFiles: boolean) => invoke<DeleteReport>('library_delete', { ids, deleteFiles }),
  librarySetMeta: (id: number, meta: { favorite?: boolean; rating?: number; note?: string }) => invoke<void>('library_set_meta', { id, ...meta }),
  librarySetTags: (id: number, tags: string[]) => invoke<void>('library_set_tags', { id, tags }),
  libraryBulkTags: (ids: number[], tags: string[], remove: boolean) => invoke<void>('library_bulk_tags', { ids, tags, remove }),
  libraryBulkFavorite: (ids: number[], favorite: boolean) => invoke<void>('library_bulk_favorite', { ids, favorite }),
  libraryTags: () => invoke<TagCount[]>('library_tags'),
  libraryRemoveMissing: () => invoke<number>('library_remove_missing'),
  libraryImport: (dir: string, recursive: boolean) => invoke<ImportReport>('library_import', { dir, recursive }),
  libraryStats: () => invoke<LibraryStats>('library_stats'),
  libraryPreview: (id: number) => invoke<string>('library_preview', { id }),
  libraryScenes: (id: number, threshold?: number) => invoke<SceneList>('library_scenes', { id, threshold }),
  librarySplitScenes: (id: number, scenes: Chapter[]) => invoke<string>('library_split_scenes', { id, scenes }),
  libraryExport: (format: 'csv' | 'json', dest: string, ids?: number[]) => invoke<number>('library_export', { format, dest, ids }),
  trashList: () => invoke<TrashItem[]>('trash_list'),
  trashRestore: (id: number) => invoke<string>('trash_restore', { id }),
  trashPurge: (id: number) => invoke<void>('trash_purge', { id }),
  trashEmpty: () => invoke<number>('trash_empty'),
  reorganizePlan: (template?: string) => invoke<MovePlan[]>('reorganize_plan', { template }),
  reorganizeApply: (plans: MovePlan[]) => invoke<MoveReport>('reorganize_apply', { plans }),
  duplicatesExact: () => invoke<DupGroup[]>('duplicates_exact'),
  duplicatesSimilar: () => invoke<DupGroup[]>('duplicates_similar'),
  cuesSearch: (query: string) => invoke<CueHit[]>('cues_search', { query }),
  cuesReindex: () => invoke<number>('cues_reindex'),
  extDataStatus: () => invoke<{ size: number; ts: number; error: string; rejectedSize: number }>('ext_data_status'),
  backupExport: (dest: string) => invoke<void>('backup_export', { dest }),
  backupImport: (src: string) => invoke<BackupInfo>('backup_import', { src }),
  videocacheInfos: (urls: string[]) => invoke<VideoCacheInfo[]>('videocache_infos', { urls }),
  videocacheGet: (url: string) => invoke<VideoCacheFull | null>('videocache_get', { url }),
  videocacheRemove: (url: string) => invoke<void>('videocache_remove', { url }),
  videocacheClear: () => invoke<void>('videocache_clear'),
  videocacheStats: () => invoke<{ videos: number; bytes: number }>('videocache_stats'),
  videocacheOpen: (url: string, sec: number, word?: string, restore?: boolean) => invoke<void>('videocache_open', { url, sec, word: word ?? null, restore: restore ?? false }),
  excerptList: () => invoke<Excerpt[]>('excerpt_list'),
  excerptAdd: (text: string, app?: string) => invoke<Excerpt>('excerpt_add', { text, app: app ?? null }),
  excerptRemove: (id: string) => invoke<void>('excerpt_remove', { id }),
  excerptNote: (id: string, note: string) => invoke<void>('excerpt_note', { id, note }),
  excerptMarkdown: () => invoke<string>('excerpt_markdown'),
  excerptExport: (dest: string) => invoke<void>('excerpt_export', { dest }),
}
