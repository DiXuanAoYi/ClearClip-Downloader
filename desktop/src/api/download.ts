import { invoke } from '@tauri-apps/api/core'
import type {
  TrackerStatus,
  TaskDetail,
  PlayerSource,
  EnqueueResult,
  OrphanPart,
  CreatorTabs,
  ListOptions,
  BatchOpts,
  BatchItem,
  BatchResult,
  BatchView,
  SiteRule,
  HealthResult,
  PlaylistEntry,
  PostOptions,
  ToolStatus,
  DetectedLink,
  HistoryItem,
  InboxCounts,
  InboxFilter,
  InboxItem,
  MediaInfo,
  TaskSnapshot,
} from '../types'

export const downloadApi = {
  detectLinks: (text: string) => invoke<DetectedLink[]>('detect_links', { text }),
  resolve: (text: string) => invoke<MediaInfo>('resolve_link', { text }),
  resolveAndEnqueue: (text: string) => invoke<string>('resolve_and_enqueue', { text }),
  enqueue: (media: MediaInfo, assetIds: string[], post?: PostOptions) => invoke<EnqueueResult>('enqueue', { media, assetIds, post }),
  batchExtract: (text: string) => invoke<string[]>('batch_extract', { text }),
  batchReadFile: (path: string) => invoke<[string[], boolean]>('batch_read_file', { path }),
  batchPreview: (key: string, urls: string[], quality: string) => invoke<void>('batch_preview', { key, urls, quality }),
  batchPreviewCancel: (key: string) => invoke<void>('batch_preview_cancel', { key }),
  batchEnqueue: (items: BatchItem[], opts: BatchOpts, source: string) => invoke<BatchResult>('batch_enqueue', { items, opts, source }),
  batchQuick: (urls: string[], source: string) => invoke<BatchResult>('batch_quick', { urls, source }),
  batchList: () => invoke<BatchView[]>('batch_list'),
  batchAction: (id: string, what: string) => invoke<void>('batch_action', { id, what }),
  batchUpdate: (id: string, opts: BatchOpts) => invoke<void>('batch_update', { id, opts }),
  batchExportFailed: (id: string) => invoke<string>('batch_export_failed', { id }),
  batchSaveText: (path: string, text: string) => invoke<void>('batch_save_text', { path, text }),
  enqueueEntries: (playlist: MediaInfo, entryIds: string[], options?: ListOptions) => invoke<number>('enqueue_entries', { playlist, entryIds, options: options ?? null }),
  creatorTabs: (url: string) => invoke<CreatorTabs>('creator_tabs', { url }),
  expandList: (url: string) => invoke<MediaInfo>('expand_list', { url }),

  toolsStatus: () => invoke<ToolStatus[]>('tools_status'),
  installTool: (tool: string) => invoke<ToolStatus>('install_tool', { tool }),
  rollbackTool: (tool: string) => invoke<ToolStatus>('rollback_tool', { tool }),
  importTool: (tool: string, path: string) => invoke<ToolStatus>('import_tool', { tool, path }),
  listExtractors: () => invoke<string[]>('list_extractors'),
  openToolsDir: () => invoke<void>('open_tools_dir'),

  listTasks: () => invoke<TaskSnapshot[]>('list_tasks'),
  pauseTask: (id: number) => invoke<void>('pause_task', { id }),
  resumeTask: (id: number) => invoke<void>('resume_task', { id }),
  cancelTask: (id: number) => invoke<void>('cancel_task', { id }),
  removeTask: (id: number) => invoke<void>('remove_task', { id }),
  clearFinished: () => invoke<void>('clear_finished'),
  playerSource: (path: string) => invoke<PlayerSource>('player_source', { path }),
  previewSource: (taskId: number) => invoke<PlayerSource>('preview_source', { taskId }),
  previewAsset: (media: MediaInfo, assetId: string, transcode = false) => invoke<PlayerSource>('preview_asset', { media, assetId, transcode }),
  taskDetail: (id: number) => invoke<TaskDetail>('task_detail', { id }),
  pauseAll: () => invoke<void>('pause_all'),
  resumeAll: () => invoke<void>('resume_all'),
  listOrphanParts: () => invoke<OrphanPart[]>('list_orphan_parts'),
  deleteOrphanParts: (paths: string[]) => invoke<number>('delete_orphan_parts', { paths }),

  inboxList: (filter?: Partial<InboxFilter>) => invoke<InboxItem[]>('inbox_list', { filter }),
  inboxCounts: () => invoke<InboxCounts>('inbox_counts'),
  inboxRetry: (ids: number[]) => invoke<number>('inbox_retry', { ids }),
  inboxRetryFailed: () => invoke<number>('inbox_retry_failed'),
  inboxIgnore: (ids: number[]) => invoke<void>('inbox_ignore', { ids }),
  inboxDelete: (ids: number[]) => invoke<void>('inbox_delete', { ids }),
  inboxClear: (scope: 'done' | 'all') => invoke<number>('inbox_clear', { scope }),
  preferredSubtitles: (media: MediaInfo) => invoke<string[]>('preferred_subtitles', { media }),
  downloadedEntries: (platform: string, entries: PlaylistEntry[]) => invoke<string[]>('downloaded_entries', { platform, entries }),
  loginSite: (text: string) => invoke<string | null>('login_site', { text }),
  listHistory: (query = '') => invoke<HistoryItem[]>('list_history', { query }),
  deleteHistory: (id: number) => invoke<void>('delete_history', { id }),
  clearHistory: () => invoke<void>('clear_history'),
  redownload: (id: number) => invoke<EnqueueResult>('redownload', { id }),
  healthCheck: () => invoke<HealthResult[]>('health_check'),
  btTrackerStatus: () => invoke<TrackerStatus>('bt_tracker_status'),
  btUpdateTrackers: () => invoke<TrackerStatus>('bt_update_trackers'),
  siteRuleTest: (rule: SiteRule, url: string) => invoke<MediaInfo>('site_rule_test', { rule, url }),
  prioritizeTask: (id: number) => invoke<void>('prioritize_task', { id }),
  moveTask: (id: number, to: 'top' | 'up' | 'down' | 'bottom') => invoke<void>('move_task', { id, to }),
  scheduleTask: (id: number, startAt: number | null) => invoke<void>('schedule_task', { id, startAt }),
  getAfterAllDone: () => invoke<string>('get_after_all_done'),
  setAfterAllDone: (action: string) => invoke<void>('set_after_all_done', { action }),
  readLinksFile: (path: string) => invoke<string>('read_links_file', { path }),
  makeSlideshow: (media: MediaInfo, imageIds: string[], musicId: string | null, seconds: number) => invoke<string>('make_slideshow', { media, imageIds, musicId, seconds }),
}
