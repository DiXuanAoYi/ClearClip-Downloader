import { invoke } from '@tauri-apps/api/core'
import type {
  AiStatus,
  PoolPreset,
  GlossaryData,
  AiExpert,
  ExpertsState,
  Glossary,
  GlossaryTerm,
  ExtractSite,
  CommunityGlossary,
  PoolStatus,
  ModelInfo,
  ProbeResult,
} from '../types'

export const aiApi = {
  sttCloudTest: (engine: 'volc' | 'xfyun' | 'xfyun_rt') => invoke<string>('stt_cloud_test', { engine }),
  secretSet: (name: string, value: string) => invoke<void>('secret_set', { name, value }),
  tmStats: () => invoke<[number, number]>('tm_stats'),
  tmClear: () => invoke<number>('tm_clear'),
  secretHas: (name: string) => invoke<boolean>('secret_has', { name }),
  aiStatus: () => invoke<AiStatus>('ai_status'),
  aiTest: () => invoke<string>('ai_test'),
  aiPoolStatus: () => invoke<PoolStatus[]>('ai_pool_status'),
  aiPoolPresets: () => invoke<PoolPreset[]>('ai_pool_presets'),
  aiPoolReset: (id: string) => invoke<void>('ai_pool_reset', { id }),
  aiPoolTest: (id: string) => invoke<string>('ai_pool_test', { id }),
  aiProbeModels: (entryId: string, baseUrl: string, apiKey: string | null) => invoke<ModelInfo[]>('ai_probe_models', { entryId, baseUrl, apiKey }),
  aiProbeTest: (entryId: string, baseUrl: string, apiKey: string | null, model: string, checkVision: boolean) =>
    invoke<ProbeResult>('ai_probe_test', { entryId, baseUrl, apiKey, model, checkVision }),
  aiPoolCopyKey: (from: string, to: string) => invoke<void>('ai_pool_copy_key', { from, to }),
  glossaryState: () => invoke<GlossaryData>('glossary_state'),
  glossarySave: (glossary: Glossary) => invoke<Glossary>('glossary_save', { glossary }),
  glossaryDelete: (id: string) => invoke<void>('glossary_delete', { id }),
  glossaryFolderAdd: (path: string) => invoke<GlossaryData>('glossary_folder_add', { path }),
  glossaryFolderRename: (from: string, to: string) => invoke<GlossaryData>('glossary_folder_rename', { from, to }),
  glossaryFolderRemove: (path: string) => invoke<GlossaryData>('glossary_folder_remove', { path }),
  glossaryImport: (text: string, name: string, into = '', lang = '') => invoke<Glossary>('glossary_import', { text, name, into, lang }),
  glossaryImportFile: (path: string, name = '', into = '', lang = '') => invoke<Glossary>('glossary_import_file', { path, name, into, lang }),
  glossaryExport: (id: string) => invoke<string>('glossary_export', { id }),
  glossaryCommunity: () => invoke<CommunityGlossary[]>('glossary_community'),
  glossaryCommunityInstall: (id: string) => invoke<Glossary>('glossary_community_install', { id }),
  glossaryExtract: (kind: 'text' | 'file' | 'url', value: string) => invoke<{ found: number; added: number; site: string }>('glossary_extract', { source: { kind, value } }),
  glossaryResolve: (ids: string[], glossaryId: string, newName: string, terms: GlossaryTerm[]) => invoke<Glossary | null>('glossary_resolve', { ids, glossaryId, newName, terms }),
  glossarySitesSave: (sites: ExtractSite[]) => invoke<void>('glossary_sites_save', { sites }),
  expertsState: () => invoke<ExpertsState>('experts_state'),
  expertsSave: (expert: AiExpert) => invoke<AiExpert>('experts_save', { expert }),
  expertsDelete: (id: string) => invoke<void>('experts_delete', { id }),
  expertsImport: (text: string) => invoke<AiExpert>('experts_import', { text }),
  expertsImportFile: (path: string) => invoke<AiExpert>('experts_import_file', { path }),
  expertsExport: (id: string) => invoke<string>('experts_export', { id }),
  expertsCommunity: () => invoke<AiExpert[]>('experts_community'),
  expertsCommunityInstall: (remoteId: string) => invoke<AiExpert>('experts_community_install', { remoteId }),
  uploadTest: () => invoke<string>('upload_test'),
  notifyTest: (id: string) => invoke<void>('notify_test', { id }),
  aiTranslate: (path: string) => invoke<number>('ai_translate', { path }),
  aiSummarize: (path: string) => invoke<number>('ai_summarize', { path }),
  aiTranscribe: (path: string, language?: string) => invoke<number>('ai_transcribe', { path, language }),
}
