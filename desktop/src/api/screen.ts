import { invoke } from '@tauri-apps/api/core'
import { listen, type UnlistenFn } from '@tauri-apps/api/event'
import type {
  ShotEntry,
  ScreenStatus,
  ScreenTarget,
  ScreenWindow,
  ScreenPayload,
  ScreenShotFrame,
  ScreenShotSaved,
  AppGlossaryPack,
  OcrPack,
  ScreenSub,
  VoiceEntry,
  ScreenPick,
  ScreenTry,
  ScreenEntry,
  OcrStatus,
  VocabStats,
  VocabWord,
  Glossary,
} from '../types'

export const screenApi = {
  shotTake: () => invoke<{ dataUrl: string; w: number; h: number } | null>('shot_take'),
  shotRun: (req: Record<string, unknown>) => invoke<number>('shot_run', { req }),
  shotPin: (dataUrl: string, x: number, y: number, w: number, h: number) => invoke<void>('shot_pin', { dataUrl, x, y, w, h }),
  shotPinTake: () => invoke<string | null>('shot_pin_take'),
  shotPinClose: () => invoke<void>('shot_pin_close'),
  shotCompare: (text: string, lang: string) => invoke<string>('shot_compare', { text, lang }),
  shotHistAdd: (src: string, text: string) => invoke<number>('shot_hist_add', { src, text }),
  shotHistList: (savedOnly?: boolean) => invoke<ShotEntry[]>('shot_hist_list', { savedOnly }),
  shotHistSave: (at: number, saved: boolean) => invoke<void>('shot_hist_save', { at, saved }),
  shotHistClear: (keepSaved?: boolean) => invoke<void>('shot_hist_clear', { keepSaved }),
  shotClose: () => invoke<void>('shot_close'),
  audioStart: () => invoke<ScreenStatus>('sc_audio_start'),
  audioStop: () => invoke<void>('sc_audio_stop'),
  voiceTranscript: () => invoke<VoiceEntry[]>('sc_audio_transcript'),
  voiceClear: () => invoke<void>('sc_audio_clear'),
  voiceExport: (kind: 'srt' | 'txt', bilingual: boolean, path: string) => invoke<number>('sc_audio_export', { kind, bilingual, path }),
  voiceSummary: () => invoke<string>('sc_audio_summary'),
  scStatus: () => invoke<ScreenStatus>('sc_status'),
  scStart: (target?: ScreenTarget, mode?: string) => invoke<ScreenStatus>('sc_start', { target, mode }),
  scStop: () => invoke<ScreenStatus>('sc_stop'),
  scToggle: () => invoke<ScreenStatus>('sc_toggle'),
  scPick: () => invoke<void>('sc_pick'),
  scSetMode: (mode: string) => invoke<ScreenStatus>('sc_set_mode', { mode }),
  scHide: (hidden?: boolean) => invoke<boolean>('sc_hide', { hidden }),
  scPause: (paused?: boolean) => invoke<boolean>('sc_pause', { paused }),
  scWindows: () => invoke<ScreenWindow[]>('sc_windows'),
  scOcrLangs: () => invoke<{ tag: string; name: string }[]>('sc_ocr_langs'),
  scOverlayState: () => invoke<ScreenPayload | null>('sc_overlay_state'),
  scShot: () => invoke<boolean>('sc_shot'),
  scShotFrame: () => invoke<ScreenShotFrame>('sc_shot_frame'),
  scShotSave: (data: string) => invoke<ScreenShotSaved>('sc_shot_save', { data }),
  glossaryAppPacks: () => invoke<AppGlossaryPack[]>('glossary_app_packs'),
  glossaryAppInstall: (ids: string[]) => invoke<number>('glossary_app_install', { ids }),
  glossaryForApp: (exe: string) => invoke<Glossary>('glossary_for_app', { exe }),
  scAckManga: () => invoke<void>('sc_ack_manga'),
  scBar: (on: boolean) => invoke<void>('sc_bar', { on }),
  floatExpand: (expanded: boolean) => invoke<void>('float_expand', { expanded }),
  floatFit: (width: number) => invoke<void>('float_fit', { width }),
  scTry: (target?: ScreenTarget) => invoke<ScreenTry>('sc_try', { target }),
  scHistory: (n?: number) => invoke<ScreenEntry[]>('sc_history', { n }),
  scHistoryClear: () => invoke<void>('sc_history_clear'),
  scCacheClear: () => invoke<void>('sc_cache_clear'),
  scPickTake: () => invoke<ScreenPick | null>('sc_pick_take'),
  scPickCancel: () => invoke<void>('sc_pick_cancel'),
  scPickDone: (rect: [number, number, number, number], hwnd: number, mode?: string) => invoke<ScreenStatus>('sc_pick_done', { rect, hwnd, mode }),
  ocrStatus: () => invoke<OcrStatus>('ocr_status'),
  ocrInstall: (zipUrl?: string, dictUrl?: string) => invoke<OcrStatus>('ocr_install', { zipUrl, dictUrl }),
  ocrImport: (kind: string, path: string) => invoke<OcrStatus>('ocr_import', { kind, path }),
  ocrRemove: () => invoke<OcrStatus>('ocr_remove'),
  ocrPacks: () => invoke<OcrPack[]>('ocr_packs'),
  ocrPackImport: (id: string, kind: 'rec' | 'dict' | 'det', path: string) => invoke<OcrPack[]>('ocr_pack_import', { id, kind, path }),
  ocrPackInstall: (id: string, recUrl: string, dictUrl: string) => invoke<OcrPack[]>('ocr_pack_install', { id, recUrl, dictUrl }),
  ocrPackRemove: (id: string) => invoke<OcrPack[]>('ocr_pack_remove', { id }),
  onScreenState: (cb: (s: ScreenStatus) => void): Promise<UnlistenFn> => listen<ScreenStatus>('live://state', (e) => cb(e.payload)),
  onScreenBlocks: (cb: (p: ScreenPayload) => void): Promise<UnlistenFn> => listen<ScreenPayload>('live://blocks', (e) => cb(e.payload)),
  onScreenSub: (cb: (p: ScreenSub) => void): Promise<UnlistenFn> => listen<ScreenSub>('live://sub', (e) => cb(e.payload)),
  onScreenShot: (cb: () => void): Promise<UnlistenFn> => listen<null>('live://shot', () => cb()),
  onScreenHidden: (cb: (h: boolean) => void): Promise<UnlistenFn> => listen<boolean>('live://hidden', (e) => cb(e.payload)),
  onOcrDownload: (cb: (p: { what: string; got: number; total: number }) => void): Promise<UnlistenFn> => listen<{ what: string; got: number; total: number }>('ocr://download', (e) => cb(e.payload)),
  vocabList: (query: string, filter: string) => invoke<VocabWord[]>('vocab_list', { query, filter }),
  vocabStats: () => invoke<VocabStats>('vocab_stats'),
  vocabRemove: (id: number) => invoke<void>('vocab_remove', { id }),
  vocabReview: (id: number, grade: number) => invoke<VocabWord>('vocab_review', { id, grade }),
  vocabAnkiPush: (deck: string, url?: string) => invoke<[number, number]>('vocab_anki_push', { deck, url }),
  vocabExport: (format: string, path: string) => invoke<string>('vocab_export', { format, path }),
}
